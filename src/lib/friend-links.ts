/**
 * 友情链接。
 *
 * 主页末尾的友链区块只读这一个数组 —— 增删改都在这里，不用碰组件。
 *
 * **空数组时整个区块不渲染**，主页上看不出曾经有过这一块。所以可以放心清空：
 * 不会在站上留下一个「友情链接」标题配一片空白的尴尬版面。
 *
 * 只有名字和地址两个字段，没有简介、没有图标 —— 展示形态就是一行内联文字链接。
 * 曾经做过卡片版（带首字色块与一句话简介），撤掉了：友链是给人顺手点开的，
 * 不是主页要推销的内容，它排在页面最末，不该比正文区块更抢眼。
 *
 * 也别再加 icon 字段。图标只能由浏览器直连对方域名去取（站点是静态导出），
 * 等于把访客的 IP 和 Referer 送给每一个友链站；对方换域名或关站，我们这边就是
 * 一排碎图，而且不会有任何人来报错。
 */

