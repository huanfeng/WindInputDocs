/**
 * 友情链接。
 *
 * 主页末尾的友链区块只读这一个数组 —— 增删改都在这里，不用碰组件。
 *
 * **空数组时整个区块不渲染**，主页上看不出曾经有过这一块。所以可以放心先合入
 * 空的：不会在站上留下一个「友情链接」标题配一片空白的尴尬版面。
 *
 * 加一条的最小写法：
 *
 *     { name: "某某输入法", url: "https://example.com" }
 *
 * `desc` 可选，但建议写 —— 友链列表最没用的形态就是一排干秃秃的站名，
 * 读者不知道点进去会看到什么。一句话说清对方是做什么的，比名字本身有用。
 *
 * 关于图标：这里**不放对方的 favicon**。理由有三，都是实打实的：
 *
 *   · 站点是静态导出的，图标只能由浏览器直连对方域名去取 —— 等于把访客的 IP
 *     和 Referer 送给每一个友链站，对方还能借此统计我们的流量。
 *   · 对方换域名、改图标路径、或者干脆关站，我们这边就是一排碎图，而且不会有
 *     任何人来报错。
 *   · 加载时机不可控，最慢的那个会拖住整块区域的观感。
 *
 * 所以卡片左侧用站名首字生成一个色块。色相由名字算出来（见组件里的 hueOf），
 * 同一个名字永远同一个颜色，不需要为每条友链手工配色。
 */

export interface FriendLink {
  /** 站点名。也是首字色块的取字来源 */
  name: string;
  url: string;
  /** 一句话说清对方是做什么的。留空则卡片只显示站名 */
  desc?: string;
}

